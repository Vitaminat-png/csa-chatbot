# Pagine prodotto del sito, per categoria
# ---------------------------------------------------------------------------
# L'elenco che il bot produce a "quali idranti fate?" si costruisce dall'indice
# delle schede tecniche. Un prodotto che il sito pubblica ma nessuna scheda
# indicizzata documenta non compariva: l'APOLLO RPC SMART rispondeva benissimo
# quando lo si nominava — la sua pagina e' nell'indice — ma spariva dagli
# elenchi. Generato da ingest/build_site_products.py.
SITE_PRODUCTS_PATH = Path(__file__).resolve().parent / "site_products.json"

try:
    _SITE_PRODUCTS: dict[str, dict] = json.loads(
        SITE_PRODUCTS_PATH.read_text(encoding="utf-8")
    )
except (FileNotFoundError, json.JSONDecodeError):
    _SITE_PRODUCTS = {}


def find_category_products(query: str) -> list[str]:
    """
    URL delle pagine prodotto della categoria che la domanda nomina.

    Gli slug sono registrati nelle quattro lingue, altrimenti "which hydrants
    do you make?" non incontrerebbe mai la parola italiana "idranti". Se la
    domanda nomina un modello preciso non si restituisce nulla: l'elenco di
    categoria servirebbe solo a diluire il contesto.
    """
    if not _SITE_PRODUCTS or find_exact_model_source(query):
        return []

    parole = set(normalize_sequence(query))
    urls: list[str] = []
    for voce in _SITE_PRODUCTS.values():
        for slug in voce.get("slug_lingue", []):
            token = normalize_sequence(slug)
            if token and _nomina_categoria(token, parole):
                urls += [pr["url"] for pr in voce.get("prodotti", [])]
                break
    return sorted(set(urls))


# Teste di slug troppo generiche per identificare da sole una categoria: chi
# scrive "valvole" sta quasi sempre parlando d'altro, e prendere l'intera
# categoria diluirebbe il contesto di quindici pagine.
_TESTE_GENERICHE = {
    "valvole", "valvola", "valves", "valve", "valvulas", "valvula",
    "vannes", "vanne", "prodotti", "products", "accessori", "accessories",
}


def _nomina_categoria(token: list[str], parole: set[str]) -> bool:
    """
    True quando la domanda nomina la categoria di quello slug.

    Pretendere tutte le parole dello slug funziona in italiano, dove sono
    slug di una parola ("idranti", "sfiati"), ma non in inglese: la categoria
    e' "pillar-fire-hydrants" e nessuno scrive "which pillar fire hydrants do
    you make". Basta allora la parola-chiave finale, purche' non sia una di
    quelle che da sole non dicono nulla.
    """
    if set(token) <= parole:
        return True
    testa = token[-1]
    return len(testa) >= 5 and testa not in _TESTE_GENERICHE and testa in parole


# ---------------------------------------------------------------------------
# Caratteristiche costruttive
# ---------------------------------------------------------------------------
# "Avete valvole convogliate?" riceveva un rifiuto mentre quattro schede lo
# sono — il concetto e' una caratteristica, e l'indice esisteva solo per le
# applicazioni. Le caratteristiche stanno nel registro, dedotte dal suffisso
# del codice (i "modelli C"), e la domanda le nomina in quattro lingue.
FEATURE_QUERY_PATTERNS: dict[str, str] = {
    "conveyed air discharge": (
        r"convogli|conveyed|air conveyance|scarico convogliato|scarico canalizzato"
        r"|achemin|canalizad"
    ),
    "anti-shock": r"anti[- ]?shock|anti[- ]?colpo d|non[- ]?slam|anti[- ]?slam|antichoc",
    "anti-surge": r"anti[- ]?surge|anti[- ]?ariete|colpo d.ariete|anti[- ]?b[eé]lier|golpe de ariete",
    "remote monitoring": (
        r"controllo remoto|telecontroll|remote (?:control|monitoring)|monitoraggio remoto"
    ),
}

_FEATURE_RX = {k: re.compile(v, re.I) for k, v in FEATURE_QUERY_PATTERNS.items()}


def find_feature_sources(query: str) -> list[str]:
    """
    Le schede che hanno la caratteristica costruttiva nominata dalla domanda.

    Non si cerca la parola nella prosa: "convogliamento" compare in trenta
    schede, quasi tutte perche' lo CITANO (un rimando, un kit accodato). Le
    otto che lo sono davvero si riconoscono dal codice, ed e' anche quello che
    intende il cliente quando dice "i modelli C".
    """
    features = _load_registry().get("features", {})
    if not features:
        return []
    trovate: set[str] = set()
    for nome, rx in _FEATURE_RX.items():
        if rx.search(query):
            trovate.update(features.get(nome, []))
    return sorted(trovate)[:MAX_FILES_PER_QUERY]


# ---------------------------------------------------------------------------
# Programmi di calcolo
# ---------------------------------------------------------------------------
# Le pagine dei programmi di dimensionamento stanno quasi tutte dietro il login,
# quindi il crawler ne indicizza un puntatore che non dice la cosa che serve:
# quali valvole quel programma dimensiona. L'indice generato da
# ingest/build_sizing_programs.py lo dice, e queste funzioni lo interrogano.
#
# Il caso d'origine: "c'e' un calcolatore per la valvola AUGUSTA?" riceveva un
# rifiuto seguito dal link al calcolatore XLC — il programma di un'altra
# famiglia, senza dire che era di un'altra famiglia.
SIZING_PATH = Path(__file__).resolve().parent / "sizing_programs.json"

_sizing: Optional[dict] = None


def _load_sizing() -> dict:
    """Carica e tiene in cache l'indice dei programmi; vuoto se manca."""
    global _sizing
    if _sizing is None:
        try:
            _sizing = json.loads(SIZING_PATH.read_text(encoding="utf-8"))
        except FileNotFoundError:
            logger.warning(
                "model_index: %s assente — indice dei programmi di calcolo "
                "disattivato. Esegui: python -m ingest.build_sizing_programs",
                SIZING_PATH.name,
            )
            _sizing = {"programmi": [], "indice_sezione": []}
        except (json.JSONDecodeError, OSError) as exc:
            logger.warning("model_index: indice dei programmi illeggibile (%s)", exc)
            _sizing = {"programmi": [], "indice_sezione": []}
    return _sizing


# "dimensionare" e "calcolare" nelle quattro lingue, piu' i nomi dei programmi.
# Volutamente stretto: "quanto pesa" non e' una domanda di dimensionamento, e
# far entrare le pagine dei programmi in ogni domanda tecnica ruberebbe uno dei
# sei slot alla scheda che porta la cifra.
_SIZING_QUERY = re.compile(
    r"\bcalcolator\w*|\bcalculator\w*|\bcalculateur\w*|\bcalculador\w*"
    r"|\bprogramm\w*\b[^.?!]{0,20}\bcalcol\w*|\bprograma\w*\b[^.?!]{0,20}\bc[aá]lculo"
    r"|\bsizing\b|\bdimension(?:o|a|amo|ate|ano|are|ato|ata|ati|amento|ando)\b"
    r"|\bdimensionn\w*|\bdimensionamiento\b|\bdimensionar\w*"
    r"|\bhow\b[^?.!]{0,30}\bsize\b|\bcsa\s+(?:cvs|lvs|rvs|prs|avs)\b",
    re.I,
)


def query_about_sizing(query: str) -> bool:
    """True quando la domanda riguarda un programma di calcolo/dimensionamento."""
    return bool(_SIZING_QUERY.search(query))


def find_sizing_programs(query: str) -> dict:
    """
    I programmi di calcolo pertinenti alla domanda.

    Restituisce sempre l'elenco completo — a chi chiede "che programmi avete?"
    servono tutti, e a chi ne chiede uno che non esiste serve sapere quali
    esistono invece di sentirsi dire "non ho informazioni". `pertinenti` sono
    quelli che dimensionano una famiglia nominata nella domanda: separarli e'
    cio' che impedisce di offrire il calcolatore XLC a chi ha chiesto della
    AUGUSTA.
    """
    if not query_about_sizing(query):
        return {}
    programmi = _load_sizing().get("programmi", [])
    if not programmi:
        return {}

    parole = set(normalize_sequence(query))
    famiglie_chieste = {
        f.upper() for f in _load_registry().get("families", {}) if f.lower() in parole
    }
    def pertinente(programma: dict) -> bool:
        if famiglie_chieste & {f.upper() for f in programma.get("famiglie", [])}:
            return True
        # Chi scrive "come dimensiono una valvola a galleggiante?" non nomina
        # nessuna serie, ma sta chiedendo esattamente il programma LVS. Vale
        # solo quando nessuna famiglia e' nominata: se la domanda dice AUGUSTA,
        # comanda la famiglia, non il tipo.
        tipo = programma.get("parole_tipo")
        return bool(tipo) and not famiglie_chieste and bool(re.search(tipo, query, re.I))

    pertinenti = [p for p in programmi if pertinente(p)]
    return {
        "pertinenti": pertinenti,
        "tutti": programmi,
        "famiglie_chieste": sorted(famiglie_chieste),
        "indice_sezione": _load_sizing().get("indice_sezione", []),
    }
